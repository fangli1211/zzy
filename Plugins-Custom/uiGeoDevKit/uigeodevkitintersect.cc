/*+
________________________________________________________________________

 断层—层位交线提取对话框实现

 计算链路（与官方 GMT 插件 gmtfault.cc:calcOnHorizon 一致）：
   EM::EMM().loadIfNotFullyLoaded(mid)
     -> EM::Horizon3D::geometry().geometryElement()  => BinIDSurface
     -> EM::Fault3D::geometry().geometryElement()    => FaultStickSurface
     -> ExplFaultStickSurface(fss, zFactor) + setCoordList + update()
     -> Geometry::FaultBinIDSurfaceIntersector(horshift,...).compute()
     -> Coord3List 中即为交线点序列

 注意：Coord3List 的点顺序由底层算法保证（已做 sortPointsToLine），
       这里不再二次排序，直接按索引输出即可。
________________________________________________________________________
-*/

